"""Actual ASGI routes and synthetic MP4; no server or GUI is launched."""
import hashlib,json,os,subprocess,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
from apps.qa_isolation import configure

class Routes(unittest.TestCase):
 def test_real_routes(self):
  with tempfile.TemporaryDirectory(prefix='PTTI-QA-') as directory:
   root=Path(directory);env={'PTTI_QA_ROOT':str(root),'PTTI_ISOLATED_QA':'1'}
   for key,part in {'PTTI_DB':'data/matches.db','PTTI_PREVIEW_QA_DB':'data/matches.db','LOCALAPPDATA':'local','WEBVIEW2_USER_DATA_FOLDER':'webview','PTTI_QA_MEDIA_ROOT':'media','PTTI_QA_LOG_ROOT':'logs','PTTI_QA_CONFIG_ROOT':'config'}.items():env[key]=str(root/part)
   configure(env)
   media=root/'media/synthetic.mp4'
   subprocess.run(['ffmpeg','-v','error','-f','lavfi','-i','testsrc2=size=160x90:rate=10','-t','2','-c:v','libx264','-pix_fmt','yuv420p',str(media)],check=True)
   (root/'config/media.json').write_text(json.dumps({media.name:hashlib.sha256(media.read_bytes()).hexdigest()}))
   with patch.dict(os.environ,env):
    from fastapi.testclient import TestClient
    from backend.main import app
    with TestClient(app) as client:
     value={'path':str(media),'rights_status':'USER_OWNED','rights_confirmed':True,'source_note':'Synthetic ffmpeg testsrc2 generated by test'}
     response=client.post('/api/video-evidence/videos',json=value)
     self.assertEqual(response.status_code,200,response.text)
     identity=response.json()['video_id']
     response=client.get('/api/video-evidence/videos/'+identity+'/media')
     self.assertEqual(response.status_code,200,response.text[:200])
     self.assertEqual(hashlib.sha256(response.content).hexdigest(),hashlib.sha256(media.read_bytes()).hexdigest())
     response=client.post('/api/video-evidence/videos',json={**value,'path':str(root.parent/'nonapproved.mp4')})
     self.assertEqual(response.status_code,400,response.text)
     for path in ['/api/vision/health','/api/professional-matches/x/video','/api/video-evidence/videos/'+identity+'/export','/api/video-evidence/imports']:
      self.assertEqual(client.get(path).status_code,403,path)
     self.assertTrue((root/'data/matches.db').is_file())
     self.assertIn("frame-src 'none'",client.get('/api/health').headers['content-security-policy'])
if __name__=='__main__':unittest.main()
