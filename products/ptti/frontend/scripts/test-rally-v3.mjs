import assert from 'node:assert/strict';
import {createReviewV2} from '../src/manualReviewV2.mjs';
import {createReviewV3,prepareReviewV3Import} from '../src/manualReviewV3.mjs';
import {createRallyPlaybackCoordinator} from '../src/rallyPlaybackCoordinator.mjs';
const media={identity:{kind:'SESSION',value:'SESSION_TOKEN_0123456789'},duration_seconds:20};
const fingerprint={algorithm:'ptti-local-video-chunks-sha256-v1',digest:'a'.repeat(64)};
const expected={digest:fingerprint.digest,duration_seconds:20};
const mark={id:'m1',seconds:1,tag:'serve',note:'note'};
const rally={id:'r1',start_seconds:1.2,end_seconds:4.5,tag:'rally',result:'won',note:'manual'};
const v2={...createReviewV2(media,[mark]),local_content_fingerprint:fingerprint};
const v3={...createReviewV3(media,[mark],[rally]),local_content_fingerprint:fingerprint};
assert.deepEqual(prepareReviewV3Import(JSON.stringify(v2),expected).rallies,[]);
assert.deepEqual(prepareReviewV3Import(JSON.stringify(v3),expected).rallies,[rally]);
assert.throws(()=>prepareReviewV3Import(JSON.stringify(v3),{...expected,digest:'b'.repeat(64)}));
assert.throws(()=>prepareReviewV3Import(JSON.stringify({...v3,schema:'ptti.manual-review/4'}),expected));
for(const bad of [{...rally,end_seconds:1.2},{...rally,end_seconds:21},{...rally,id:'m1'},{...rally,start_seconds:NaN},{...rally,result:'invented'}])assert.throws(()=>createReviewV3(media,[mark],[bad]));
let cancelled=0,paused=0,pending,played=[];
const adapter={cancelPendingSeek(){if(pending){pending({ok:false,error:'cancelled'});pending=null}},seekExact(){return new Promise(resolve=>pending=resolve)}};
const core={getSnapshot:()=>({status:'ready',video_identity:'fingerprint',duration_seconds:20}),pause:()=>paused++,playRallyPlaylist:(items,opts)=>{played.push({items,opts});return {ok:true,value:{done:new Promise(()=>{}),pause(){},resume:async()=>({ok:true}),cancel(){cancelled++}}}}};
const c=createRallyPlaybackCoordinator(core,adapter);
assert.equal(c.playRally(rally,'other').error,'identity-mismatch');
const old=c.playRally(rally,'fingerprint',{repeat:true});assert.equal(old.ok,true);assert.equal(played[0].opts.repeat_single,true);
const seek=c.seekMoment(2);assert.equal(cancelled,1);c.cancel();assert.deepEqual(await seek,{ok:false,error:'cancelled'});
const fresh=c.playRally(rally,'fingerprint');old.value.cancel();assert.equal(cancelled,1);fresh.value.cancel();assert.equal(cancelled,2);assert.ok(paused>=1);
console.log('PASS v2 compatibility, v3 rally identity and boundary checks, playback arbitration and cancellation');
