import assert from 'node:assert/strict';
import {createMatch,createPrediction,readArenaSnapshot,sanitizeArenaState,scoreHistory,saveArenaState,advanceToCriticalResolved} from '../src/fanArenaEngine.mjs';
const match=createMatch(1);
assert.equal(saveArenaState(undefined,{match,predictions:[],history:[]}),false,'missing storage must never report a successful save');
const modern=createPrediction([],match,'FIRST_TO_GAME_POINT','A').prediction;
const old={...modern,id:`${match.id}:FIRST_TO_MATCH_POINT:first-match-point`,type:'FIRST_TO_MATCH_POINT',target:'first-match-point'};
const migrated=sanitizeArenaState({match,predictions:[old,modern],history:[]});
assert.equal(migrated.predictions.length,1,'legacy and canonical aliases identify the same locked prediction');
assert.ok(createPrediction(migrated.predictions,match,'FIRST_TO_GAME_POINT','B').errors.length,'migration cannot reopen the same prediction');
const resolved={...modern,status:'RESOLVED',correct:true,resolvedAt:new Date(1).toISOString()};
assert.equal(scoreHistory([resolved,resolved]).total,1,'repeated settlement IDs never inflate accuracy');
assert.equal(sanitizeArenaState({match,predictions:[{...modern,type:'NEXT_POINT',target:'point-999'}],history:[]}).predictions.length,0);
const next=createPrediction([],match,'NEXT_POINT','A').prediction;
assert.equal(sanitizeArenaState({match,predictions:[next,{...next,id:'alias',target:'point-00'}],history:[]}).predictions.length,1,'numeric target aliases cannot create duplicate events');
let reads=0,writes=0;
const archive=JSON.stringify({match,predictions:[modern],history:[resolved]});
const storage={getItem(){reads++;return archive},setItem(){writes++}};
const snapshot=readArenaSnapshot(storage);
assert.equal(reads,1,'one snapshot read supplies match, predictions and history');
assert.equal(writes,0,'hydration never writes over a saved archive');
assert.equal(snapshot.predictions[0].status,'RESOLVED','resolved history cannot become pending again');
assert.equal(scoreHistory(snapshot.history).total,1);
for(let i=0;i<3;i++)readArenaSnapshot(storage);
assert.equal(writes,0,'repeat initialization is read-only, including StrictMode');
const damaged=readArenaSnapshot({getItem(){return '{broken'},setItem(){throw Error('must not overwrite')}});
assert.equal(damaged.writable,false);
assert.ok(damaged.error);
const conflicting={...resolved,correct:false};
assert.equal(scoreHistory([resolved,conflicting]).total,0,'contradictory duplicate outcomes are not counted');
assert.equal(readArenaSnapshot({getItem(){return JSON.stringify({match,predictions:[],history:[resolved,conflicting]})},setItem(){writes++}}).writable,false,'conflicting archives are preserved rather than silently rewritten');
assert.equal(readArenaSnapshot({getItem(){return JSON.stringify({match,predictions:[{bad:true}],history:[]})},setItem(){writes++}}).writable,false);
assert.equal(sanitizeArenaState({match,predictions:[modern],history:[{...resolved,choice:'B'}]}).history.length,0);
const ff=advanceToCriticalResolved(match,createPrediction([],match,'NEXT_POINT','A').predictions);
const repeated=advanceToCriticalResolved(ff.match,ff.predictions);
assert.equal(repeated.resolved.length,0,'fast forward never settles the first prediction twice');
console.log('Arena storage: missing storage, legacy aliases, duplicate IDs and invalid targets PASS');
