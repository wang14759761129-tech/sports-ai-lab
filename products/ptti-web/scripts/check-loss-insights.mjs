import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { importQuickAnnotationDraft } from '../src/local-video-review.mjs';
import { summarizeObservedLosses } from '../src/local-loss-insights.mjs';

const input = JSON.parse(await readFile(new URL('./fixtures/goal10-5-19-point-simulated.json', import.meta.url), 'utf8'));
const imported = importQuickAnnotationDraft(input);
assert.equal(imported.ok, true);
const points = imported.value.points;
const p = (number) => points[number - 1].point_id;
const stage = 'END_AFTER_3_4_CONTACTS';
const annotated = points.map((point) => [p(2), p(8)].includes(point.point_id) ? { ...point, observed_rally_stage: stage } : point);
const playable = [p(2), p(10), p(17)];
const a = summarizeObservedLosses(annotated, 1, 'PLAYER_A', playable);
assert.deepEqual([a.recorded, a.all.wins, a.all.losses, a.all.playable_loss_ids.length], [19, 11, 8, 2]);
assert.deepEqual([a.stages[stage].wins, a.stages[stage].losses], [0, 3]);
assert.deepEqual(a.stages[stage].loss_point_ids, [p(2), p(8), p(10)]);
assert.deepEqual(a.stages[stage].playable_loss_ids, [p(2), p(10)]);
assert.equal(a.unknown_stages, 15);
assert.equal(a.unknown_winners, 0);
assert.equal(annotated.every((point) => point.observed_tactics.third_ball_attack === 'unknown'), true);
const b = summarizeObservedLosses(annotated, 1, 'PLAYER_B', playable);
assert.deepEqual([b.all.wins, b.all.losses, b.all.playable_loss_ids.length], [8, 11, 1]);
assert.equal(b.stages[stage].losses, 0);
const revoked = summarizeObservedLosses(annotated, 1, 'PLAYER_A', [p(10), p(17)]);
assert.equal(revoked.stages[stage].losses, 3);
assert.deepEqual(revoked.stages[stage].playable_loss_ids, [p(10)]);
const changed = summarizeObservedLosses(annotated.map((point) => point.point_id === p(2) ? { ...point, winner: 'PLAYER_A' } : point), 1, 'PLAYER_A', [p(10), p(17)]);
assert.deepEqual(changed.stages[stage].loss_point_ids, [p(8), p(10)]);
assert.deepEqual([changed.all.wins, changed.all.losses], [12, 7]);
const unknown = summarizeObservedLosses([{ ...annotated[1], winner: 'UNKNOWN' }, { ...annotated[7], observed_rally_stage: 'NOT_A_STAGE' }], 1, 'PLAYER_A', playable);
assert.equal(unknown.recorded, 1);
assert.equal(unknown.unknown_winners, 1);
assert.equal(unknown.unknown_stages, 1);
assert.equal(unknown.stages[stage].losses, 0);
assert.equal(summarizeObservedLosses(annotated, 2, 'PLAYER_A', playable).recorded, 0);
assert.equal(summarizeObservedLosses(annotated, 1, 'UNKNOWN', playable).recorded, 0);
assert.equal(summarizeObservedLosses(annotated, 1, 'PLAYER_A', []).all.playable_loss_ids.length, 0);
assert.equal(points[1].observed_rally_stage, 'END_AFTER_1_2_CONTACTS', 'original input remains intact');
console.log('Loss insights PASS: 19-point fixture, both observers, stage counts, unknowns, game isolation, binding revocation, winner correction and unbound import.');
