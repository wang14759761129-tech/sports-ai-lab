import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { consumeReadonlyProjection } from '../src/readonly-catalog.mjs';
const index = process.argv.indexOf('--source-dir');
if (index < 0 || !process.argv[index + 1]) throw new Error('Use --source-dir <producer products/ptti-integration directory>');
const source = resolve(process.argv[index + 1]);
const root = fileURLToPath(new URL('..', import.meta.url));
const names = ['web-internal-review.json','web-strict-public.json'];
const bytes = await Promise.all(names.map(name => readFile(resolve(source,'generated/alpha-rc',name))));
const review = JSON.parse(bytes[0]), strict = JSON.parse(bytes[1]);
const reviewed = consumeReadonlyProjection(review,{view:'review',localReview:true});
const publicCatalog = consumeReadonlyProjection(strict);
if (publicCatalog.matches.length !== strict.matches.length || publicCatalog.matches.reduce((n,m)=>n+m.sources.length,0) !== strict.video_sources.length) throw new Error('Producer public JSON contains unauthorized rows');
const doc = await readFile(resolve(source,'ALPHA_RC_BRIDGE.md'));
const snapshot = resolve(root,'.alpha-qa/bridge'); await mkdir(snapshot,{recursive:true});
for(let i=0;i<names.length;i++) await writeFile(resolve(snapshot,names[i]),bytes[i]);
await writeFile(resolve(snapshot,'ALPHA_RC_BRIDGE.md'),doc);
await writeFile(resolve(root,'public/data/web-strict-public.json'),bytes[1]);
const manifest = Object.fromEntries(names.map((name,i)=>[name,createHash('sha256').update(bytes[i]).digest('hex')]));
await writeFile(resolve(snapshot,'manifest.json'),JSON.stringify(manifest,null,2));
console.log(JSON.stringify({reviewMatches:reviewed.matches.length,publicMatches:publicCatalog.matches.length,sha256:manifest},null,2));
console.log('Read-only producer import: review stays in ignored .alpha-qa; only strict public is copied to public/. No source file is changed.');
